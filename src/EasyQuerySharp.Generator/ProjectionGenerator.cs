using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace EasyQuerySharp.Generator;

/// <summary>
/// 为 <c>[Projection]</c> 方法产出表达式树（见 0002）：在所在的 partial 类型里生成一个模块初始化方法，
/// 把方法体原样写成 <c>Expression&lt;Func&lt;…&gt;&gt;</c> 登记到 <c>ProjectionRegistry</c>；查询里调用该方法时内联成这棵表达式。
/// 方法体在原来的类型与 using 下编译，名字解析与原方法一致。
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class ProjectionGenerator : IIncrementalGenerator
{
    private const string AttributeName = "EasyQuerySharp.ProjectionAttribute";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var methods = context.SyntaxProvider.ForAttributeWithMetadataName(AttributeName,
            static (node, _) => node is MethodDeclarationSyntax,
            static (ctx, _) => Describe((MethodDeclarationSyntax)ctx.TargetNode, (IMethodSymbol)ctx.TargetSymbol));
        context.RegisterSourceOutput(methods.Collect(), static (spc, all) => Emit(spc, all));
    }

    // 一个 [Projection] 方法：可以生成时带上生成所需的文本，否则带上不能生成的原因
    private sealed class Projection(string? hintName, string? source, Location location, string methodName, string? problem)
    {
        public string? HintName { get; } = hintName;

        public string? Source { get; } = source;

        public Location Location { get; } = location;

        public string MethodName { get; } = methodName;

        public string? Problem { get; } = problem;
    }

    private static Projection Describe(MethodDeclarationSyntax syntax, IMethodSymbol method)
    {
        var location = syntax.Identifier.GetLocation();
        Projection Fail(string problem) => new(null, null, location, method.Name, problem);

        if (!method.IsStatic) return Fail("必须是静态方法");
        if (method.IsGenericMethod) return Fail("不能是泛型方法");
        if (method.ReturnsVoid) return Fail("必须有返回值");
        if (method.Parameters.Any(p => p.RefKind != RefKind.None)) return Fail("不能有 ref / out / in 参数");
        var body = syntax.ExpressionBody?.Expression
                   ?? (syntax.Body?.Statements is { Count: 1 } statements && statements[0] is ReturnStatementSyntax { Expression: { } returned } ? returned : null);
        if (body is null) return Fail("的方法体只能有一个表达式（=> 表达式，或只有一句 return）");

        var types = new List<INamedTypeSymbol>();
        for (var type = method.ContainingType; type is not null; type = type.ContainingType) types.Insert(0, type);
        foreach (var type in types)
        {
            if (type.IsGenericType) return Fail($"所在的类型 {type.Name} 不能是泛型");
            if (!type.DeclaringSyntaxReferences.Any(r => r.GetSyntax() is TypeDeclarationSyntax t && t.Modifiers.Any(SyntaxKind.PartialKeyword)))
                return Fail($"所在的类型 {type.Name} 要声明为 partial");
        }

        var format = SymbolDisplayFormat.FullyQualifiedFormat.AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);
        var delegateType = "global::System.Func<" + string.Join(", ", method.Parameters.Select(p => p.Type.ToDisplayString(format)).Append(method.ReturnType.ToDisplayString(format))) + ">";
        var parameters = string.Join(", ", method.Parameters.Select(p => p.Type.ToDisplayString(format) + " " + SyntaxFacts.GetKeywordKind(p.Name) switch
        {
            SyntaxKind.None => p.Name,
            _ => "@" + p.Name,
        }));

        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        // 原文件的 using（方法体按原来的名字解析）
        if (syntax.SyntaxTree.GetRoot() is CompilationUnitSyntax unit)
            foreach (var u in unit.Usings) source.Append(u.ToFullString().Trim()).Append('\n');
        var ns = method.ContainingNamespace.IsGlobalNamespace ? null : method.ContainingNamespace.ToDisplayString();
        if (ns is not null) source.Append("namespace ").Append(ns).Append(";\n");
        foreach (var type in types) source.Append("partial ").Append(Keyword(type)).Append(' ').Append(type.Name).Append("\n{\n");
        var id = method.Name + "_" + (uint)syntax.SpanStart;
        source.Append("    [global::System.Runtime.CompilerServices.ModuleInitializer]\n")
            .Append("    internal static void __EqsRegisterProjection_").Append(id).Append("() =>\n")
            .Append("        global::EasyQuerySharp.ProjectionRegistry.Register(new ").Append(delegateType).Append('(').Append(method.Name).Append("),\n")
            .Append("            (global::System.Linq.Expressions.Expression<").Append(delegateType).Append(">)((").Append(parameters).Append(") =>\n")
            .Append("#line ").Append(body.GetLocation().GetLineSpan().StartLinePosition.Line + 1).Append(" \"").Append(syntax.SyntaxTree.FilePath.Replace("\\", "\\\\")).Append("\"\n")
            .Append(body.ToFullString().Trim()).Append("\n#line default\n            ));\n");
        foreach (var _ in types) source.Append("}\n");

        var hint = string.Join(".", types.Select(t => t.Name)) + "." + id + ".Projection.g.cs";
        return new Projection(hint, source.ToString(), location, method.Name, null);
    }

    private static string Keyword(INamedTypeSymbol type) => type switch
    {
        { IsRecord: true, TypeKind: TypeKind.Struct } => "record struct",
        { IsRecord: true } => "record",
        { TypeKind: TypeKind.Struct } => "struct",
        { TypeKind: TypeKind.Interface } => "interface",
        _ => "class",
    };

    private static void Emit(SourceProductionContext context, ImmutableArray<Projection> projections)
    {
        foreach (var projection in projections)
        {
            if (projection.Problem is { } problem)
                context.ReportDiagnostic(Diagnostic.Create(Descriptors.UnsupportedProjection, projection.Location, projection.MethodName, problem));
            else context.AddSource(projection.HintName!, projection.Source!);
        }
    }
}
