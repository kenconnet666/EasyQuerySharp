using System.Text;
using EasyQuerySharp.Metadata;

namespace EasyQuerySharp.Dialects;

// DDL（code-first）：建表、注释、索引、外键、同步用的改名与加列、删表、列类型、读库结构的查询
public abstract partial class SqlDialect
{
    /// <summary>
    /// 建表语句。默认是标准写法：每列 <c>"列" 类型 NULL|NOT NULL</c>，最后是主键约束；注释、索引、外键是另外的语句。
    /// MySQL、PostgreSQL、SQLite 覆盖成 Java 版的多行格式。
    /// </summary>
    public virtual string CreateTableSql(EntityMetadata entity)
    {
        var lines = TableColumns(entity).Select(c => ColumnDefinition(entity, c)).ToList();
        if (entity.KeyColumns.Count > 0 && !entity.KeyColumns.Any(InlinePrimaryKey))
            lines.Add($"PRIMARY KEY ({string.Join(",", entity.KeyColumns.Select(k => QuoteIdentifier(k.Name)))})");
        return CreateTableStatement(entity, string.Join(", ", lines));
    }

    /// <summary>包住列定义的建表语句；默认 <c>CREATE TABLE IF NOT EXISTS</c>，不支持 IF NOT EXISTS 的库（SQL Server）覆盖。</summary>
    protected virtual string CreateTableStatement(EntityMetadata entity, string body) =>
        $"CREATE TABLE IF NOT EXISTS {QualifiedTable(entity)} ({body})";

    /// <summary>一列的定义：<c>"列" 类型 [自增] NULL|NOT NULL</c>。<paramref name="entity"/> 供需要按表建附属对象的方言用（DuckDB 的自增序列）。</summary>
    protected virtual string ColumnDefinition(EntityMetadata entity, ColumnMetadata column) =>
        $"{QuoteIdentifier(column.Name)} {ColumnType(column)}{(column.IsGenerated ? " " + IdentityClause : "")} {(IsNullable(column) ? "NULL" : "NOT NULL")}";

    /// <summary>自增列的写法；默认是标准 SQL 的 <c>GENERATED BY DEFAULT AS IDENTITY</c>（PG、Oracle、Db2、H2）。</summary>
    protected virtual string IdentityClause => "GENERATED BY DEFAULT AS IDENTITY";

    /// <summary>主键是否已经写在列定义里（SQLite 的 <c>INTEGER PRIMARY KEY AUTOINCREMENT</c>），是的话不再单独写主键约束。</summary>
    protected virtual bool InlinePrimaryKey(ColumnMetadata key) => false;

    /// <summary>删表语句（表不存在时不报错）。</summary>
    public virtual string DropTableIfExistsSql(EntityMetadata entity) => $"DROP TABLE IF EXISTS {QualifiedTable(entity)}";

    /// <summary>表里真有的列：计算列（<see cref="ComputedAttribute"/>）只在查询里展开，不建。</summary>
    internal static IEnumerable<ColumnMetadata> TableColumns(EntityMetadata entity) => entity.Columns.Where(c => c.Computed is null);

    /// <summary>表注释的语句；默认 <c>COMMENT ON TABLE … IS '…'</c>，注释写在建表语句里的方言（MySQL、PostgreSQL）或没有注释的方言返回 null。</summary>
    internal virtual string? TableCommentSql(EntityMetadata entity) =>
        entity.Comment is null ? null : $"COMMENT ON TABLE {QualifiedTable(entity)} IS {SqlString(entity.Comment)}";

    /// <summary>列注释的语句；默认 <c>COMMENT ON COLUMN … IS '…'</c>，规则同 <see cref="TableCommentSql"/>。</summary>
    internal virtual string? ColumnCommentSql(EntityMetadata entity, ColumnMetadata column) =>
        column.Comment is null ? null : $"COMMENT ON COLUMN {QualifiedTable(entity)}.{QuoteIdentifier(column.Name)} IS {SqlString(column.Comment)}";

    /// <summary>建索引：<c>CREATE [UNIQUE] INDEX "名" ON 表 ("列" ASC, …)</c>。</summary>
    internal virtual string CreateIndexSql(EntityMetadata entity, IndexMetadata index) =>
        $"CREATE {(index.Unique ? "UNIQUE " : "")}INDEX {QuoteIdentifier(index.Name)} ON {QualifiedTable(entity)} ({IndexColumns(index, ", ")})";

    /// <summary>索引的列：<c>"列" ASC</c> / <c>"列" DESC</c>。</summary>
    private protected string IndexColumns(IndexMetadata index, string separator) =>
        string.Join(separator, index.Columns.Select(c => $"{QuoteIdentifier(c.Column.Name)} {(c.Descending ? "DESC" : "ASC")}"));

    /// <summary>外键是否只能写在建表语句里（SQLite、DuckDB 不能给已有的表加外键）。</summary>
    internal virtual bool InlineForeignKeys => false;

    /// <summary>给已有的表加外键：<c>ALTER TABLE 表 ADD CONSTRAINT "名" FOREIGN KEY (…) REFERENCES 目标 (…) [动作]</c>。</summary>
    internal virtual string AddForeignKeySql(ForeignKeyMetadata foreignKey) =>
        $"ALTER TABLE {QualifiedTable(foreignKey.Entity)} ADD CONSTRAINT {QuoteIdentifier(foreignKey.Name)} FOREIGN KEY ({QuotedNames(foreignKey.Columns)}) "
        + $"REFERENCES {QualifiedTable(foreignKey.Target)} ({QuotedNames(foreignKey.TargetColumns)}){(foreignKey.Action is null ? "" : " " + foreignKey.Action)}";

    /// <summary>逗号分隔的列名（加引号）。</summary>
    private protected string QuotedNames(IEnumerable<ColumnMetadata> columns, string separator = ",") =>
        string.Join(separator, columns.Select(c => QuoteIdentifier(c.Name)));

    /// <summary>同步时把旧表改成实体的表名：<c>ALTER TABLE 旧表 RENAME TO 新表</c>。</summary>
    internal virtual string RenameTableSql(EntityMetadata entity, string oldName) =>
        $"ALTER TABLE {QualifiedName(entity.Schema, oldName)} RENAME TO {QualifiedTable(entity)}";

    /// <summary>同步时把旧列改成实体的列名：<c>ALTER TABLE 表 RENAME COLUMN 旧列 TO 新列</c>。</summary>
    internal virtual string RenameColumnSql(EntityMetadata entity, string oldName, ColumnMetadata column) =>
        $"ALTER TABLE {QualifiedTable(entity)} RENAME COLUMN {QuoteIdentifier(oldName)} TO {QuoteIdentifier(column.Name)}";

    /// <summary>同步时加列：<c>ALTER TABLE 表 ADD COLUMN 列定义</c>。</summary>
    internal virtual string AddColumnSql(EntityMetadata entity, ColumnMetadata column) =>
        $"ALTER TABLE {QualifiedTable(entity)} ADD COLUMN {ColumnDefinition(entity, column)}";

    /// <summary>
    /// 读库结构（当前 schema）的四条查询，列名约定见 <see cref="CatalogQueries"/>；不支持读结构的方言返回 null。
    /// </summary>
    internal virtual CatalogQueries? CatalogQueries => null;

    /// <summary>SQL 字符串字面量（单引号加倍）；注释等 DDL 里的文字用，不是参数。</summary>
    private protected virtual string SqlString(string text) => "'" + text.Replace("'", "''", StringComparison.Ordinal) + "'";

    /// <summary>
    /// Java 版的多行建表格式（MySQL、PostgreSQL、SQLite、DuckDB 共用）：<c>CREATE TABLE IF NOT EXISTS 表 ( </c> 之后每列一行
    /// <c>"列" 类型 NULL|NOT NULL 附加,</c>，主键约束单独一行（列之间 <c>", "</c>），没有主键时去掉最后一列的逗号，
    /// 外键只能写在建表语句里的方言接着写外键，最后换行写 <paramref name="tail"/>。
    /// </summary>
    private protected string MultiLineCreateTable(EntityMetadata entity, Func<ColumnMetadata, string> columnTail, string tail)
    {
        var sql = new StringBuilder("CREATE TABLE IF NOT EXISTS ").Append(QualifiedTable(entity)).Append(" ( ");
        foreach (var c in TableColumns(entity))
        {
            sql.Append('\n');
            if (InlinePrimaryKey(c)) sql.Append(ColumnDefinition(entity, c));
            else sql.Append(QuoteIdentifier(c.Name)).Append(' ').Append(ColumnType(c)).Append(IsNullable(c) ? " NULL " : " NOT NULL ").Append(columnTail(c));
            sql.Append(',');
        }
        var keys = entity.KeyColumns.Where(k => !InlinePrimaryKey(k)).ToList();
        if (keys.Count > 0) sql.Append(" \n PRIMARY KEY (").Append(string.Join(", ", keys.Select(k => QuoteIdentifier(k.Name)))).Append(')');
        else sql.Length--;
        if (InlineForeignKeys)
            foreach (var fk in entity.ForeignKeys)
                sql.Append("\n, FOREIGN KEY (").Append(QuotedNames(fk.Columns)).Append(") REFERENCES ").Append(QualifiedTable(fk.Target))
                    .Append('(').Append(QuotedNames(fk.TargetColumns)).Append(')').Append(fk.Action is null ? "" : " " + fk.Action + " ");
        return sql.Append('\n').Append(tail).ToString();
    }

    /// <summary>列的数据库类型：<see cref="ColumnAttribute.DbType"/> 优先，否则按 CLR 类型映射（<see cref="ClrColumnType"/>）。</summary>
    public string ColumnType(ColumnMetadata column) =>
        column.DbType ?? ClrColumnType(Nullable.GetUnderlyingType(column.Converter?.ProviderType ?? column.ClrType) ?? column.Converter?.ProviderType ?? column.ClrType, column);

    /// <summary>CLR 类型到列类型的默认映射。默认用标准 SQL 类型名。</summary>
    protected virtual string ClrColumnType(Type type, ColumnMetadata column) => type switch
    {
        _ when type == typeof(string) => "VARCHAR(255)",
        _ when type == typeof(int) || type.IsEnum => "INTEGER",
        _ when type == typeof(long) => "BIGINT",
        _ when type == typeof(short) => "SMALLINT",
        _ when type == typeof(byte) || type == typeof(sbyte) => "SMALLINT",
        _ when type == typeof(bool) => "BOOLEAN",
        _ when type == typeof(decimal) => "DECIMAL(16,2)",
        _ when type == typeof(double) => "DOUBLE PRECISION",
        _ when type == typeof(float) => "REAL",
        _ when type == typeof(DateTime) => "TIMESTAMP",
        _ when type == typeof(DateTimeOffset) => "TIMESTAMP WITH TIME ZONE",
        _ when type == typeof(DateOnly) => "DATE",
        _ when type == typeof(TimeOnly) || type == typeof(TimeSpan) => "TIME",
        _ when type == typeof(Guid) => "CHAR(36)",
        _ when type == typeof(byte[]) => "BLOB",
        _ => throw new NotSupportedException($"{column} 的类型 {type.Name} 没有默认的列类型，请用 [Column(DbType = …)] 指定"),
    };

    /// <summary>列是否可空：主键与非可空值类型不可空，其余可空（与 Java 版一致）；可空的值对象里的列都可空。</summary>
    protected static bool IsNullable(ColumnMetadata column) =>
        !column.IsPrimaryKey && (column.InNullableValueObject || !column.ClrType.IsValueType || Nullable.GetUnderlyingType(column.ClrType) is not null);

    /// <inheritdoc cref="IsNullable"/>
    internal static bool ColumnNullable(ColumnMetadata column) => IsNullable(column);
}

/// <summary>
/// 读库结构的四条查询（当前 schema 的普通表），各自按表、位置排好序，列用约定的别名：
/// 表 <c>table_name, comment</c>；列 <c>table_name, column_name, column_type, is_nullable, column_default, comment, is_generated, primary_key</c>；
/// 索引（不含主键）<c>table_name, index_name, is_unique, column_name</c>；外键 <c>table_name, constraint_name, column_name, referenced_table, referenced_column</c>
/// （没有外键的库为 null）。
/// </summary>
internal sealed record CatalogQueries(string Tables, string Columns, string Indexes, string? ForeignKeys);
